#!/usr/bin/env python3
"""Turn Vitis HLS's xfaceshield_scrubber_hw.h into src/pl_scrubber_regs.hpp.

Usage: gen_regs.py path/to/xfaceshield_scrubber_hw.h > src/pl_scrubber_regs.hpp
"""

import re
import sys

PREFIX = "XFACESHIELD_SCRUBBER_CTRL_ADDR_"
SCALARS = [
    ("kWidth", "WIDTH"), ("kHeight", "HEIGHT"), ("kFillY", "FILL_Y"),
    ("kFillC", "FILL_C"), ("kMaxAgeFrames", "MAX_AGE_FRAMES"),
    ("kNumBoxes", "NUM_BOXES"), ("kCommitSeq", "COMMIT_SEQ"),
    ("kFrames", "FRAMES"), ("kBlankedFrames", "BLANKED_FRAMES"),
    ("kFramesSinceCommit", "FRAMES_SINCE_COMMIT"), ("kLatchedSeq", "LATCHED_SEQ"),
]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    text = open(sys.argv[1]).read()
    offsets = {name: int(value, 16) for name, value in re.findall(
        r"#define\s+" + PREFIX + r"(\w+)_DATA\s+0x([0-9a-fA-F]+)", text)}

    def get(name):
        if name not in offsets:
            sys.exit(f"{PREFIX}{name}_DATA not found in {sys.argv[1]}")
        return offsets[name]

    out = ["// AXI-Lite register offsets of the faceshield_scrubber HLS IP.",
           f"// GENERATED by pl/scrubber/gen_regs.py from {sys.argv[1].split('/')[-1]}.",
           "#pragma once", "", "#include <cstdint>", "",
           "namespace faceshield::pl_regs {", "", "constexpr bool kGenerated = true;", ""]
    for const, reg in SCALARS:
        out.append(f"constexpr uint32_t {const} = 0x{get(reg):x};")
    for axis in "XY":
        values = ", ".join(f"0x{get(f'BOX{b}_{axis}'):x}" for b in range(8))
        out.append(f"constexpr uint32_t kBox{axis}[8] = {{{values}}};")
    span = (max(offsets.values()) + 8 + 0xff) & ~0xff
    out += [f"constexpr uint32_t kSpan = 0x{span:x};  // bytes to map", "",
            "}  // namespace faceshield::pl_regs"]
    print("\n".join(out))


if __name__ == "__main__":
    main()
